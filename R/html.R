# Minimal self-contained HTML report builder (no pandoc needed).

#' Save a ggplot/patchwork to PNG and return the path
#' @param p plot
#' @param path file
#' @param w width (in)
#' @param h height (in)
#' @export
mf_save_plot <- function(p, path, w = 7, h = 5) {
  dir.create(dirname(path), showWarnings = FALSE, recursive = TRUE)
  ggplot2::ggsave(path, p, width = w, height = h, dpi = 150, bg = "white")
  path
}

img_tag <- function(path, width = "100%") {
  if (is.null(path) || !file.exists(path)) return("")
  b64 <- base64enc_file(path)
  sprintf('<img src="data:image/png;base64,%s" style="max-width:%s"/>', b64, width)
}

base64enc_file <- function(path) {
  raw <- readBin(path, "raw", file.info(path)$size)
  jsonlite::base64_enc(raw)
}

html_table <- function(df, digits = 3, max_rows = 50) {
  if (is.null(df) || !nrow(df)) return("<p><i>No rows.</i></p>")
  df <- utils::head(as.data.frame(df), max_rows)
  for (c in names(df)) if (is.numeric(df[[c]])) df[[c]] <- ifelse(abs(df[[c]]) < 1e-3 & df[[c]] != 0,
                                                                   formatC(df[[c]], format = "e", digits = 2),
                                                                   formatC(df[[c]], format = "fg", digits = digits))
  hdr <- paste0("<tr>", paste0("<th>", htmltools::htmlEscape(names(df)), "</th>", collapse = ""), "</tr>")
  rows <- apply(df, 1, function(r) paste0("<tr>", paste0("<td>", htmltools::htmlEscape(as.character(r)), "</td>", collapse = ""), "</tr>"))
  paste0('<div class="tw"><table>', hdr, paste(rows, collapse = ""), "</table></div>")
}

#' Build a self-contained HTML report
#' @param path output .html
#' @param title title
#' @param sections list of lists with heading, html (text), plots (png paths), tables (named list of data.frames)
#' @param subtitle optional HTML shown under the title
#' @export
mf_html_report <- function(path, title, sections, subtitle = NULL) {
  css <- "body{font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif;max-width:1100px;margin:30px auto;padding:0 20px;color:#222;line-height:1.45}
h1{border-bottom:3px solid #2c7fb8;padding-bottom:6px}h2{color:#2c7fb8;margin-top:36px;border-bottom:1px solid #ddd}
table{border-collapse:collapse;font-size:12px;margin:8px 0}th,td{border:1px solid #ccc;padding:3px 7px;text-align:left}
th{background:#f0f4f8}.tw{overflow-x:auto;max-height:520px}.box{background:#f7fbff;border-left:4px solid #2c7fb8;padding:8px 14px;margin:12px 0}
.warn{background:#fff8e6;border-left:4px solid #e6a000;padding:8px 14px;margin:12px 0}nav a{margin-right:12px;font-size:13px}"
  toc <- paste0("<nav>", paste0(sprintf('<a href="#s%d">%s</a>', seq_along(sections),
                                        vapply(sections, function(s) htmltools::htmlEscape(s$heading), "")), collapse = ""), "</nav>")
  body <- vapply(seq_along(sections), function(i) {
    s <- sections[[i]]
    paste0(sprintf('<h2 id="s%d">%s</h2>', i, htmltools::htmlEscape(s$heading)), s$html %||% "",
           paste(vapply(s$plots %||% list(), img_tag, ""), collapse = "\n"),
           paste(vapply(names(s$tables %||% list()), function(n) paste0("<h4>", htmltools::htmlEscape(n), "</h4>", html_table(s$tables[[n]])), ""), collapse = "\n"))
  }, "")
  html <- paste0("<!DOCTYPE html><html><head><meta charset='utf-8'><title>", htmltools::htmlEscape(title),
                 "</title><style>", css, "</style></head><body><h1>", htmltools::htmlEscape(title), "</h1>",
                 if (!is.null(subtitle)) paste0("<p>", subtitle, "</p>") else "",
                 toc, paste(body, collapse = "\n"),
                 "<hr><p style='font-size:11px;color:#777'>Generated by methylflow ", as.character(utils::packageVersion("methylflow")),
                 " on ", format(Sys.time(), "%Y-%m-%d %H:%M"), "</p></body></html>")
  writeLines(html, path)
  invisible(path)
}
